package com.techtsunagu.wakatta.feature.course.data

import com.techtsunagu.wakatta.core.model.Tri
import com.techtsunagu.wakatta.feature.course.domain.Course
import com.techtsunagu.wakatta.feature.course.domain.CourseSummary
import com.techtsunagu.wakatta.feature.course.domain.Drill
import com.techtsunagu.wakatta.feature.course.domain.InspectItem
import com.techtsunagu.wakatta.feature.course.domain.InspectSpot
import com.techtsunagu.wakatta.feature.course.domain.Panel
import com.techtsunagu.wakatta.feature.course.domain.SpotItem
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/** Reads the bundled course JSON (generated by tools/gen-courses.mjs). Throws on malformed content. */
internal object CourseParser {

    fun parseSummaries(text: String): List<CourseSummary> =
        Json.parseToJsonElement(text).jsonArray.map { summary(it.jsonObject) }

    fun parseCourse(text: String): Course {
        val o = Json.parseToJsonElement(text).jsonObject
        return Course(
            summary = summary(o),
            panels = o.list("panels").map { Panel(it.str("who"), it.tri("text")) },
            handbook = o.array("handbook").map(::tri),
            reel = o.array("reel").map(::tri),
            drills = o.list("drills").map(::drill),
            inspect = o.list("inspect").map(::inspectItem),
        )
    }

    private fun summary(o: JsonObject) = CourseSummary(
        id = o.str("id"), category = o.str("category"), level = o.int("level"), minutes = o.int("minutes"),
        title = o.tri("title"), sub = o.tri("sub"),
    )

    private fun drill(o: JsonObject): Drill {
        val id = o.str("id")
        val name = o.tri("name")
        val goal = o.tri("goal")
        return when (val kind = o.str("kind")) {
            "spot" -> Drill.Spot(
                id, name, goal, o.int("secs"), o.int("need"),
                o.list("items").map { SpotItem(it.tri("label"), it["hazard"]!!.jsonPrimitive.boolean) },
            )
            "seq" -> Drill.Seq(id, name, goal, o.array("steps").map(::tri))
            "reflex" -> Drill.Reflex(id, name, goal)
            "ring" -> Drill.Ring(id, name, goal, o.array("wheels").map { it.jsonPrimitive.boolean })
            "sling" -> Drill.Sling(id, name, goal, o.int("loadKg"), o.int("wllKg"))
            else -> throw IllegalArgumentException("unknown drill kind $kind")
        }
    }

    private fun inspectItem(o: JsonObject) = InspectItem(
        id = o.str("id"),
        name = o.tri("name"),
        defective = o["defective"]!!.jsonPrimitive.boolean,
        spots = o.list("spots").map { InspectSpot(it.int("x"), it.int("y"), it.tri("check")) },
    )

    private fun JsonObject.str(key: String) = getValue(key).jsonPrimitive.content
    private fun JsonObject.int(key: String) = getValue(key).jsonPrimitive.int
    private fun JsonObject.array(key: String): JsonArray = getValue(key).jsonArray
    private fun JsonObject.list(key: String): List<JsonObject> = array(key).map { it.jsonObject }
    private fun JsonObject.tri(key: String): Tri = tri(getValue(key))
    private fun tri(e: JsonElement): Tri = e.jsonObject.mapValues { it.value.jsonPrimitive.content }
}
